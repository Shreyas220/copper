//! Embeds every file under `ui/` into the kiln binary, so the console ships
//! with the daemon and needs no separate install or build step.

use std::fmt::Write;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=ui");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("ui");
    let mut files = vec![];
    collect(&root, &root, &mut files);
    files.sort();
    let mut out = String::from("/// (path under ui/, contents), generated by build.rs.\npub static FILES: &[(&str, &[u8])] = &[\n");
    for rel in files {
        let abs = root.join(&rel);
        writeln!(out, "    ({rel:?}, include_bytes!({:?})),", abs.display().to_string()).unwrap();
    }
    out.push_str("];\n");
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("ui_files.rs"), out).unwrap();
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else {
            out.push(path.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/"));
        }
    }
}
